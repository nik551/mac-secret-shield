    func testSlowCheckReleasesChangedRegionsBlackedOut() {
        let frame = Frame(pixelBuffer: Self.render(["export API_KEY=" + SecretDetectorTests.fake(32)]), captureTime: Frame.now())
        let out = released(frame, recognizer: FakeRecognizer(delay: 0.5), budget: 0.1, wait: 0.8)
        XCTAssertEqual(out.count, 2, "blacked out at the deadline, then the checked version once the late check finished")
        let (safe, stats, at) = out[0]
        XCTAssertEqual(stats.failClosedFrames, 1)
        XCTAssertLessThan(at - frame.captureTime, 0.3)
        XCTAssertTrue(Self.isBlack(safe.pixelBuffer, x: 20, y: 20)) // first frame: everything changed
        XCTAssertTrue(Self.isBlack(safe.pixelBuffer, x: 1900, y: 390))
        // Nothing newer arrived (a still screen sends no frames), so the mirror must not stay stuck on black.
        XCTAssertGreaterThanOrEqual(out[1].2 - frame.captureTime, 0.5)
        XCTAssertFalse(Self.isBlack(out[1].0.pixelBuffer, x: 1900, y: 390))
    }

