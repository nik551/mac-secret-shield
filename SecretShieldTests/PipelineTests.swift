    func testTilesCoverTheRegionAndOwnEveryLineOnce() {
        let region = CGRect(x: 100, y: 0, width: 2880, height: 1800)
        let rows = VisionTextRecognizer.tileRows(for: region)
        let tiles = rows.flatMap(\.tiles)
        XCTAssertTrue(tiles.allSatisfy { $0.width <= VisionTextRecognizer.maxTileWidth + 0.001 && $0.height <= VisionTextRecognizer.maxTileHeight + 0.001 })
        let union = tiles.reduce(CGRect.null) { $0.union($1) }
        XCTAssertEqual(union.minX, region.minX, accuracy: 0.001)
        XCTAssertEqual(union.maxX, region.maxX, accuracy: 0.001)
        XCTAssertEqual(union.maxY, region.maxY, accuracy: 0.001)
        for y: CGFloat in [0, 333.3, 1799, 900, 868] { XCTAssertEqual(rows.filter { $0.owns.contains(y) }.count, 1, "\(y)") }
        XCTAssertGreaterThan(rows.count, 1, "region should need more than one row of tiles for this test")
