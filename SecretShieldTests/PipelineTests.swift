    /// Records which regions it was asked to OCR; reports `line` only on the first call.
    final class RecordingRecognizer: TextRecognizer, @unchecked Sendable {
        let line: TextLine
        let calls = OSAllocatedUnfairLock(initialState: [[CGRect]]())
        init(line: TextLine) { self.line = line }
        func recognize(_ frame: Frame, in regions: [CGRect]) throws -> [TextLine] {
            // Also "reads" all other text on screen (as one box), so UnreadText has nothing to black out.
        calls.withLock { $0.append(regions); return ($0.count == 1 ? [line] : []) + [TextLine(text: "ordinary output", rect: CGRect(x: 0, y: 0, width: 1920, height: 1080))] }
        }
    }

    func testScrollingReusesTheCheckAndMovesRedactionsWithTheText() {
        let lines = (0..<20).map { "line \($0): some ordinary terminal output \(SecretDetectorTests.fake($0 + 5))" }
        // The detector is fed a fake OCR line on the first check: a secret on rows 100...120.
        let secret = TextLine(text: "export API_KEY=" + SecretDetectorTests.fake(32), rect: CGRect(x: 100, y: 100, width: 470, height: 20))
        let recognizer = RecordingRecognizer(line: secret)
        let out = OSAllocatedUnfairLock(initialState: [Frame]())
        let buffer = DelayBuffer(budget: 0.3, recognizer: recognizer, detector: detector, windowSource: FakeWindows(windows: [Self.terminal])) { f, _ in
            out.withLock { $0.append(f) }
        }
        buffer.submit(Frame(pixelBuffer: Self.render(lines), captureTime: Frame.now()))
        Thread.sleep(forTimeInterval: 0.2)
        // Scroll by one line (18 px) and print one new line at the bottom.
        buffer.submit(Frame(pixelBuffer: Self.render(Array(lines.dropFirst()) + ["a brand new line"]), captureTime: Frame.now()))
        Thread.sleep(forTimeInterval: 0.2)

        let calls = recognizer.calls.withLock { $0 }
        XCTAssertEqual(calls.count, 2)
        let secondOCRHeight = calls.last!.reduce(0) { $0 + $1.height }
        XCTAssertLessThan(secondOCRHeight, 120, "only the new line (plus context) should be OCR'd, not the whole scrolled area")
        let frames = out.withLock { $0 }
        XCTAssertEqual(frames.count, 2)
        XCTAssertTrue(Self.isBlack(frames[1].pixelBuffer, x: 300, y: 110 - 18), "the redaction should move up with its text")
        XCTAssertFalse(Self.isBlack(frames[1].pixelBuffer, x: 300, y: 130), "and not stay at its old place")
    }

    final class MovableWindows: WindowSource, @unchecked Sendable {
