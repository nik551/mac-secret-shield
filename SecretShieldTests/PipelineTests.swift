    func replayFixtureInTerminal(columns: Int) throws {
        let env = try Self.fixture("fake.env"), pem = try Self.fixture("fake_key.pem")
        let jwt = String(env.first { $0.hasPrefix("JWT_TOKEN=") }!.dropFirst("JWT_TOKEN=".count))
        var transcript: [String] = ["$ cat .env"]
        transcript += env
        transcript += ["$ printenv", "HOME=/Users/dev", "PORT=3000"]
        transcript += env.filter { !$0.hasPrefix("#") }
        transcript += ["$ cat deploy_key.pem"]
        transcript += pem
        transcript += ["$ echo $JWT_TOKEN", jwt, "$ "]
        let visibleRows = 22
        let window = CGRect(x: 0, y: 0, width: 8 + CGFloat(columns) * 7.224 + 14, height: 24 + CGFloat(visibleRows) * 18)
        let terminal = WindowInfo(bundleID: "com.apple.Terminal", frame: window)

        let released = OSAllocatedUnfairLock(initialState: [Frame]())
        let buffer = DelayBuffer(recognizer: VisionTextRecognizer(), detector: detector, windowSource: FakeWindows(windows: [terminal])) { f, _ in
            released.withLock { $0.append(f) }
        }
        var rows: [String] = []
        for line in transcript {
            var rest = Substring(line)
            repeat { rows.append(String(rest.prefix(columns))); rest = rest.dropFirst(columns) } while !rest.isEmpty
            let frame = Self.render(Array(rows.suffix(visibleRows)), width: 1920, height: 1080)
            buffer.submit(Frame(pixelBuffer: frame, captureTime: Frame.now()))
            Thread.sleep(forTimeInterval: 0.9)
        }

        let values: [String] = env.filter { !$0.hasPrefix("#") }.compactMap { $0.split(separator: "=", maxSplits: 1).last.map(String.init) }
        var secrets: [String] = values.map { $0.contains("@") ? String($0.split(separator: ":")[2].split(separator: "@")[0]) : $0 }
        secrets += pem.filter { !$0.hasPrefix("-----") }
        let fragments = secrets.map { secret -> [String] in
            let core = Array(secret.dropFirst(min(13, secret.count / 3)))
            return stride(from: 0, through: max(0, core.count - 10), by: 1).map { String(core[$0..<min(core.count, $0 + 10)]) }
        }
        let recognizer = VisionTextRecognizer()
        var leaks: [String] = []
        for (n, frame) in released.withLock({ $0 }).enumerated() {
            let seen = try recognizer.recognize(frame, in: [window]).map(\.text).joined().filter { !$0.isWhitespace }
            for (secret, frags) in zip(secrets, fragments) where frags.contains(where: seen.contains) {
                leaks.append("frame \(n): \(secret.prefix(8))…")
            }
        }
        XCTAssertGreaterThan(released.withLock { $0.count }, transcript.count / 2)
        let last = try recognizer.recognize(released.withLock { $0.last! }, in: [window]).map(\.text).joined()
        XCTAssertTrue(last.contains("deploy_key"), "ordinary text should stay visible, not be blacked out")
        XCTAssertEqual(leaks, [])
    }
