    func testRestOfAWrappedKeyStaysCoveredAfterItsFirstRowScrollsAway() {
        let window = CGRect(x: 0, y: 0, width: 600, height: 300)
        let key = "sk-ant-api03-" + SecretDetectorTests.fake(60)
        let first = "ANTHROPIC_API_KEY=" + String(key.prefix(53)), rest = String(key.dropFirst(53)) // 71 + 20 chars
        let a = TextLine(text: first, rect: CGRect(x: 10, y: 10, width: 568, height: 14))
        let b = TextLine(text: rest, rect: CGRect(x: 10, y: 28, width: 160, height: 14))
        let before = DelayBuffer.detect(in: [a, b], window: window, detector: detector, remembered: [])
        XCTAssertTrue(before.rects.contains { $0.intersects(a.rect) } && before.rects.contains { $0.intersects(b.rect) })
        // Later, only the continuation row is on screen (in a different place) and is read on its own.
        let alone = TextLine(text: rest, rect: CGRect(x: 10, y: 10, width: 160, height: 14))
        XCTAssertEqual(DelayBuffer.detect(in: [alone], window: window, detector: detector, remembered: []).rects.count, 0,
                       "on its own the continuation looks like nothing")
        XCTAssertFalse(DelayBuffer.detect(in: [alone], window: window, detector: detector, remembered: before.secrets).rects.isEmpty)
        // OCR reads it slightly differently next time (l → 1): still matched.
        let misread = TextLine(text: rest.replacingOccurrences(of: "l", with: "1"), rect: alone.rect)
        XCTAssertFalse(DelayBuffer.detect(in: [misread], window: window, detector: detector, remembered: before.secrets).rects.isEmpty)
        // Ordinary text doesn't match a remembered secret.
        let other = TextLine(text: "deploying build to staging", rect: alone.rect)
        XCTAssertEqual(DelayBuffer.detect(in: [other], window: window, detector: detector, remembered: before.secrets).rects.count, 0)
    }

