        func windows(frameSize: CGSize) -> [WindowInfo]? { current.withLock { $0 } }
    }

    func testMovedTerminalIsReadInFullAndOldRedactionsDropped() {
        let windows = MovableWindows()
        windows.current.withLock { $0 = [WindowInfo(bundleID: "com.apple.Terminal", frame: CGRect(x: 0, y: 0, width: 700, height: 300))] }
        let secret = TextLine(text: "export API_KEY=" + SecretDetectorTests.fake(32), rect: CGRect(x: 100, y: 100, width: 470, height: 20))
        let recognizer = RecordingRecognizer(line: secret)
        let out = OSAllocatedUnfairLock(initialState: [Frame]())
        let buffer = DelayBuffer(budget: 0.3, recognizer: recognizer, detector: detector, windowSource: windows) { f, _ in out.withLock { $0.append(f) } }
        buffer.submit(Frame(pixelBuffer: Self.render(["a", "b"]), captureTime: Frame.now()))
        Thread.sleep(forTimeInterval: 0.2)
        let moved = CGRect(x: 300, y: 50, width: 700, height: 300) // dragged
        windows.current.withLock { $0 = [WindowInfo(bundleID: "com.apple.Terminal", frame: moved)] }
        buffer.submit(Frame(pixelBuffer: Self.render(["moved", "window"]), captureTime: Frame.now()))
        Thread.sleep(forTimeInterval: 0.2)

        let calls = recognizer.calls.withLock { $0 }
        XCTAssertEqual(calls.count, 2)
        let read = calls[1].reduce(CGRect.null) { $0.union($1) }
        XCTAssertTrue(read.contains(moved.intersection(CGRect(x: 0, y: 0, width: 1920, height: 400))), "the whole moved window is re-read")
        XCTAssertFalse(Self.isBlack(out.withLock { $0 }.last!.pixelBuffer, x: 300, y: 110), "the old block doesn't stay behind")
    }

    func testRowMatchingFindsScrolledRows() {
