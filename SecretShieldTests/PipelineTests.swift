    /// A BGRA frame with `lines` drawn in 12 pt Menlo, light on dark, like a terminal at 1x.
    static func render(_ lines: [String], width: Int = 1920, height: Int = 400, fontSize: CGFloat = 12) -> CVPixelBuffer {
        var buffer: CVPixelBuffer?
        CVPixelBufferCreate(nil, width, height, kCVPixelFormatType_32BGRA,
                            [kCVPixelBufferIOSurfacePropertiesKey: [:]] as CFDictionary, &buffer)
        let pb = buffer!
        CVPixelBufferLockBaseAddress(pb, [])
        let ctx = CGContext(data: CVPixelBufferGetBaseAddress(pb), width: width, height: height, bitsPerComponent: 8,
                            bytesPerRow: CVPixelBufferGetBytesPerRow(pb), space: CGColorSpaceCreateDeviceRGB(),
                            bitmapInfo: CGImageAlphaInfo.premultipliedFirst.rawValue | CGBitmapInfo.byteOrder32Little.rawValue)!
        NSGraphicsContext.current = NSGraphicsContext(cgContext: ctx, flipped: false)
        NSColor(white: 0.12, alpha: 1).setFill()
        NSRect(x: 0, y: 0, width: width, height: height).fill()
        let attributes: [NSAttributedString.Key: Any] = [.font: NSFont(name: "Menlo", size: fontSize)!, .foregroundColor: NSColor(white: 0.9, alpha: 1)]
        for (i, line) in lines.enumerated() {
            (line as NSString).draw(at: NSPoint(x: 8, y: CGFloat(height) - 24 - CGFloat(i) * fontSize * 1.5), withAttributes: attributes)
        }
        NSGraphicsContext.current = nil
        CVPixelBufferUnlockBaseAddress(pb, [])
        return pb
    }

    /// Lines of a TestFixtures file, generated by make-fixtures.sh if missing (they're not committed).
    static func fixture(_ name: String) throws -> [String] {
        let folder = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent().appending(path: "TestFixtures")
        let url = folder.appending(path: name)
        if !FileManager.default.fileExists(atPath: url.path) {
            let generate = Process()
            generate.executableURL = folder.appending(path: "make-fixtures.sh")
            try generate.run()
            generate.waitUntilExit()
        }
        return try String(contentsOf: url, encoding: .utf8).split(separator: "\n").map(String.init)
    }

    static func pixel(_ pb: CVPixelBuffer, x: Int, y: Int) -> (b: UInt8, g: UInt8, r: UInt8) {
        CVPixelBufferLockBaseAddress(pb, .readOnly)
        defer { CVPixelBufferUnlockBaseAddress(pb, .readOnly) }
        let p = CVPixelBufferGetBaseAddress(pb)!.assumingMemoryBound(to: UInt8.self) + y * CVPixelBufferGetBytesPerRow(pb) + x * 4
        return (p[0], p[1], p[2])
    }

    static func isBlack(_ pb: CVPixelBuffer, x: Int, y: Int) -> Bool {
        let p = pixel(pb, x: x, y: y)
        return p.r == 0 && p.g == 0 && p.b == 0
    }

    struct FakeRecognizer: TextRecognizer {
        var delay: TimeInterval = 0
        var lines: [TextLine] = []
        func recognize(_ frame: Frame, in regions: [CGRect]) throws -> [TextLine] {
            Thread.sleep(forTimeInterval: delay)
            return lines
        }
    }

    struct FakeWindows: WindowSource {
        var windows: [WindowInfo]?
        func windows(frameSize: CGSize) -> [WindowInfo]? { windows }
    }

    static let terminal = WindowInfo(bundleID: "com.apple.Terminal", frame: CGRect(x: 0, y: 0, width: 1920, height: 400))

    /// Runs one frame through a DelayBuffer and returns every frame it released.
    func released(_ frame: Frame, recognizer: FakeRecognizer, windows: [WindowInfo]? = [terminal],
                  budget: CFTimeInterval, wait: TimeInterval) -> [(Frame, PipelineStats, CFTimeInterval)] {
        let out = OSAllocatedUnfairLock(initialState: [(Frame, PipelineStats, CFTimeInterval)]())
        let buffer = DelayBuffer(budget: budget, recognizer: recognizer, detector: detector,
                                 windowSource: FakeWindows(windows: windows)) { frame, stats in
            out.withLock { $0.append((frame, stats, Frame.now())) }
        }
        buffer.submit(frame)
        Thread.sleep(forTimeInterval: wait)
        return out.withLock { $0 }
    }

