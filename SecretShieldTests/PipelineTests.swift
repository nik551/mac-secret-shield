    /// Renders FAKE secrets as a full-width terminal, runs real OCR + detection + redaction, then OCRs the
    /// output again and checks no secret is readable while normal text still is.
    func testEndToEndNoSeededSecretIsReadableAfterRedaction() throws {
        let secrets = ["sk-proj-" + SecretDetectorTests.fake(48), "AKIA" + SecretDetectorTests.fake(16).uppercased(),
                       "ghp_" + SecretDetectorTests.fake(36), "xoxb-123456789012-" + SecretDetectorTests.fake(24),
                       "sk_live_" + SecretDetectorTests.fake(40)]
        // ~120 chars of ordinary text first, so this key straddles a seam between OCR tiles.
        let padding = "deploying build 4821 to the staging cluster and waiting for health checks to pass before merging, then"
        let lines = ["$ printenv", "NODE_ENV=production", "OPENAI_API_KEY=" + secrets[0], "AWS_ACCESS_KEY_ID=" + secrets[1],
                     "PORT=3000", "GITHUB_TOKEN=" + secrets[2], "SLACK_BOT_TOKEN=" + secrets[3],
                     padding + " using key " + secrets[4] + " for billing"]
        let frame = Frame(pixelBuffer: Self.render(lines), captureTime: Frame.now())
        let bands = [CGRect(x: 0, y: 0, width: 1920, height: 400)]

        let recognizer = VisionTextRecognizer()
        let start = Frame.now()
        let rects = try DelayBuffer.secretRects(in: frame, bands: bands, windows: [Self.terminal], recognizer: recognizer, detector: detector)
        print(String(format: "OCR + detection, 1920x400 terminal: %.0f ms", (Frame.now() - start) * 1000))
        let safe = try XCTUnwrap(Redactor().redact(frame, covering: rects))

        // OCR sometimes inserts spaces ("OPENAI_ API_KEY"), so compare without whitespace.
        let seen = try recognizer.recognize(safe, in: bands).map(\.text).joined().filter { !$0.isWhitespace }
        XCTAssertTrue(seen.contains("NODE_ENV"), "OCR read nothing, so the check below would be meaningless")
        XCTAssertTrue(seen.contains("OPENAI_API_KE"), "the key name should stay visible") // last glyph touches the block
        XCTAssertTrue(seen.contains("thenusing") && seen.contains("forbilling"), "text around the seam-crossing key should stay visible")
        for secret in secrets {
            XCTAssertFalse(seen.contains(secret.suffix(12)), "readable after redaction: \(secret.prefix(6))…")
        }
    }

    /// Same as the live leak check, in-process: every seeded secret in TestFixtures, printed in a full-screen
    /// terminal at 1x, must be unreadable after OCR → detection → redaction.
    func testFixtureSecretsAreUnreadableAfterRedaction() throws {
        let env = try Self.fixture("fake.env"), pem = try Self.fixture("fake_key.pem")
        let screen = ["$ cat .env"] + env + ["$ cat deploy_key.pem"] + pem
        let frame = Frame(pixelBuffer: Self.render(screen, height: 1080), captureTime: Frame.now())
        let whole = [CGRect(x: 0, y: 0, width: 1920, height: 1080)]
        let screenWindow = WindowInfo(bundleID: "com.googlecode.iterm2", frame: whole[0])

        let recognizer = VisionTextRecognizer()
        let rects = try DelayBuffer.secretRects(in: frame, bands: whole, windows: [screenWindow], recognizer: recognizer, detector: detector)
        let safe = try XCTUnwrap(Redactor().redact(frame, covering: rects))
        let seen = try recognizer.recognize(safe, in: whole).map(\.text).joined().filter { !$0.isWhitespace }

        XCTAssertTrue(seen.contains("OPENAI_API_KEY") && seen.contains("$cat.env"), "OCR read nothing, so the check below would be meaningless")
        let secrets = env.filter { !$0.hasPrefix("#") }.compactMap { $0.split(separator: "=", maxSplits: 1).last.map(String.init) }
            .map { $0.contains("@") ? String($0.split(separator: ":")[2].split(separator: "@")[0]) : $0 } // URL: password only
            + pem.filter { !$0.hasPrefix("-----") }
        for secret in secrets {
            let core = Array(secret.dropFirst(min(13, secret.count / 3))) // skip "sk-proj-"-style prefixes
            let leaked = stride(from: 0, through: max(0, core.count - 10), by: 1).contains { seen.contains(String(core[$0..<min(core.count, $0 + 10)])) }
            XCTAssertFalse(leaked, "readable after redaction: \(secret.prefix(8))…")
        }
    }

